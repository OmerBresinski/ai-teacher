/*
 * Writes `src/icons/concepts.ts` from the pilot's `pilot-concepts.json` (TEACH-310 part b). Run once
 * per backfill batch: `bun scripts/icon-concepts.ts <path to pilot-concepts.json>`. Only `id`,
 * `label`, `synonyms`, `lesson` and `keyStage` are kept; the output is formatted by Biome after.
 */
import { readFileSync, writeFileSync } from "node:fs";

interface RawConcept {
  id: string;
  label: string;
  synonyms: string[];
  lesson: string;
  keyStage: string;
}

const source = process.argv[2];
if (!source) throw new Error("usage: bun scripts/icon-concepts.ts <pilot-concepts.json>");
const raw = JSON.parse(readFileSync(source, "utf8")) as RawConcept[];
const rows = raw.map(({ id, label, synonyms, lesson, keyStage }) => ({
  id,
  label,
  synonyms,
  lesson,
  keyStage,
}));
const out = `// GENERATED by scripts/icon-concepts.ts from the pilot's pilot-concepts.json. Do not edit by hand.
import type { IconConcept } from "./types";

export const ICON_CONCEPTS: readonly IconConcept[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(new URL("../src/icons/concepts.ts", import.meta.url), out);
console.log(`wrote ${rows.length} concepts`);
