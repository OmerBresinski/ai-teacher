#!/usr/bin/env bun
/**
 * Regenerates `src/catalogue.gen.ts`: each `gen_<ev>` event the lesson pipeline logs, and the
 * literal property names its `ev` object carries (ADR 0041). Those names are the event's
 * allowlist; nothing else is sent. Run after adding or changing an `ev` log line:
 *
 *   bun packages/observability/scripts/catalogue.ts
 *
 * `src/catalogue.test.ts` fails when the committed file no longer matches the source. The script
 * formats its output with Biome, as the pre-commit hook would.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { Glob } from "bun";
import { CONTENT_KEYS, eventNameOf } from "../src/events";

const ROOT = join(import.meta.dirname, "../../generation/src");
const OUT = join(import.meta.dirname, "../src/catalogue.gen.ts");

/** The object literal that opens before `at` (balanced braces), or "" when there is none. */
function enclosing(src: string, at: number): string {
  const start = src.lastIndexOf("{", at);
  let depth = 0;
  for (let i = start; i < Math.min(src.length, start + 1500); i++) {
    if (src[i] === "{") depth += 1;
    else if (src[i] === "}") {
      depth -= 1;
      if (depth === 0) return src.slice(start + 1, i);
    }
  }
  return "";
}

/** The top-level keys of an object literal body (nested objects and calls stripped). */
function keysOf(body: string): string[] {
  let flat = body;
  for (let i = 0; i < 3; i++) flat = flat.replace(/\{[^{}]*\}/g, "").replace(/\([^()]*\)/g, "");
  const keys: string[] = [];
  for (const m of flat
    .replace(/\n/g, " ")
    .matchAll(/(?:^|,)\s*(\.\.\.)?([A-Za-z_][A-Za-z0-9_]*)\s*(?=:|,|$)/g)) {
    // A spread (`...counts(…)`) names no property; its keys are listed by hand in `events.ts`.
    if (m[1]) continue;
    const k = m[2] ?? "";
    if (k && k !== "ev" && !keys.includes(k)) keys.push(k);
  }
  return keys;
}

export function scan(): Record<string, string[]> {
  const events: Record<string, Set<string>> = {};
  for (const file of new Glob("**/*.ts").scanSync(ROOT)) {
    if (file.includes(".test.") || file.includes("fixtures")) continue;
    const src = readFileSync(join(ROOT, file), "utf8");
    for (const m of src.matchAll(
      /ev:\s*(?:[^,"]*\?\s*)?"([a-z0-9-]+)"(?:\s*:\s*"([a-z0-9-]+)")?/g,
    )) {
      const keys = keysOf(enclosing(src, m.index ?? 0)).filter(
        (k) => !CONTENT_KEYS.has(k.toLowerCase()),
      );
      for (const ev of [m[1], m[2]]) {
        const name = ev ? eventNameOf(ev) : undefined;
        if (!name) continue;
        events[name] ??= new Set();
        for (const k of keys) events[name].add(k);
      }
    }
  }
  return Object.fromEntries(
    Object.keys(events)
      .sort()
      .map((e) => [e, [...(events[e] ?? [])].sort()]),
  );
}

export function render(events: Record<string, string[]>): string {
  const lines = Object.entries(events).map(
    ([e, keys]) => `  ${e}: [${keys.map((k) => JSON.stringify(k)).join(", ")}],`,
  );
  return `// GENERATED by packages/observability/scripts/catalogue.ts from the \`ev\` log lines in
// ${relative(join(import.meta.dirname, "../../.."), ROOT)}. Do not edit; re-run the script.
/** Each pipeline \`gen_*\` event and the property names it may carry (ADR 0041). */
export const EVENT_KEYS: Record<string, readonly string[]> = {
${lines.join("\n")}
};
`;
}

if (import.meta.main) {
  writeFileSync(OUT, render(scan()));
  Bun.spawnSync(["bunx", "biome", "format", "--write", OUT]);
}
