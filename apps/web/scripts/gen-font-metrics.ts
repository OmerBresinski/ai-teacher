import { readFileSync, writeFileSync } from "node:fs";
import { chromium } from "@playwright/test";

/**
 * Regenerates `packages/slides/src/font-metrics.generated.ts` (TEACH-70): measures every theme
 * font's printable ASCII advances in Chromium. Run from `apps/web`: `bun scripts/gen-font-metrics.ts`.
 */
const REPO = new URL("../../../", import.meta.url).pathname;
const ROOT = `${REPO}node_modules/.bun`;
const FONTS: Record<string, string> = {
  lexend: "lexend",
  gabarito: "gabarito",
  figtree: "figtree",
  sourceSerif: "source-serif-4",
  schibsted: "schibsted-grotesk",
  literata: "literata",
  publicSans: "public-sans",
  bricolage: "bricolage-grotesque",
  instrumentSans: "instrument-sans",
  atkinson: "atkinson-hyperlegible-next",
  fredoka: "fredoka",
  playpen: "playpen-sans",
  baloo: "baloo-2",
  nunito: "nunito",
  outfit: "outfit",
};
/**
 * Static families (no variable build): one file per weight. A weight with no file renders in the
 * nearest face the browser picks (600 in Andika's 700), which is what is measured.
 */
const STATIC_FONTS: Record<string, { pkg: string; weights: number[] }> = {
  andika: { pkg: "andika", weights: [400, 700] },
};
const WEIGHTS = [400, 600, 700];
const CHARS = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)).join("");

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent("<html><body></body></html>");
const out: Record<string, Record<number, number[]>> = {};
type Face = { b64: string; weight: string };
const faces: [string, Face[]][] = [
  ...Object.entries(FONTS).map(([key, pkg]): [string, Face[]] => [
    key,
    [
      {
        b64: readFileSync(
          `${ROOT}/@fontsource-variable+${pkg}@5.3.0/node_modules/@fontsource-variable/${pkg}/files/${pkg}-latin-wght-normal.woff2`,
        ).toString("base64"),
        weight: "100 900",
      },
    ],
  ]),
  ...Object.entries(STATIC_FONTS).map(([key, { pkg, weights }]): [string, Face[]] => [
    key,
    weights.map((w) => ({
      b64: readFileSync(
        `${ROOT}/@fontsource+${pkg}@5.3.0/node_modules/@fontsource/${pkg}/files/${pkg}-latin-${w}-normal.woff2`,
      ).toString("base64"),
      weight: String(w),
    })),
  ]),
];
for (const [key, list] of faces) {
  out[key] = await page.evaluate(
    async ({ key, list, WEIGHTS, CHARS }) => {
      for (const { b64, weight } of list) {
        const bytes = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
        const face = new FontFace(`m-${key}`, bytes.buffer, { weight });
        await face.load();
        document.fonts.add(face);
      }
      const ctx = document.createElement("canvas").getContext("2d");
      if (!ctx) throw new Error("no canvas");
      const res: Record<number, number[]> = {};
      for (const w of WEIGHTS) {
        ctx.font = `${w} 1000px "m-${key}"`;
        res[w] = [...CHARS].map((c) => Math.round(ctx.measureText(c).width));
      }
      return res;
    },
    { key, list, WEIGHTS, CHARS },
  );
}
await browser.close();

const lines = Object.entries(out).map(
  ([key, byWeight]) =>
    `  ${key}: {\n${Object.entries(byWeight)
      .map(([w, arr]) => `    ${w}: [${arr.join(", ")}],`)
      .join("\n")}\n  },`,
);
writeFileSync(
  `${REPO}packages/slides/src/font-metrics.generated.ts`,
  `/*
 * GENERATED by \`apps/web/scripts/gen-font-metrics.ts\`, measuring the theme fonts (the \`@fontsource-variable/*\` latin files the editor
 * loads) in Chromium: the advance width of every printable ASCII character, U+0020 to U+007E, in
 * thousandths of an em, at weights 400, 600 and 700. Do not edit by hand.
 */
import type { FontKey } from "./fonts";

export const ADVANCES: Partial<Record<FontKey, Record<400 | 600 | 700, readonly number[]>>> = {
${lines.join("\n")}
};
`,
);
console.log("ok", Object.keys(out).length);
